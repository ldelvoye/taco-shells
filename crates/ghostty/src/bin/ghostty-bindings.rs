//! Regenerates `src/sys.rs` from the headers of the library this crate links. Run it as `cargo xtask ghostty-bindings`.

const HEADER_LINE: &str = "/* generated by rust-bindgen from libghostty-vt's <ghostty/vt.h>; regenerate with `cargo xtask ghostty-bindings` */";

fn main() {
    let include = env!("TACO_GHOSTTY_INCLUDE");
    let header = format!("{include}/ghostty/vt.h");
    let include_flag = format!("-I{include}");
    let builder = bindgen::Builder::default()
        .header(header)
        .clang_arg(include_flag)
        .allowlist_function("ghostty_.*")
        .allowlist_type("Ghostty.*")
        .allowlist_var("GHOSTTY_.*")
        .disable_header_comment()
        .raw_line(HEADER_LINE);
    let bindings = builder.generate().expect("generate the bindings");

    let output = concat!(env!("CARGO_MANIFEST_DIR"), "/src/sys.rs");
    bindings.write_to_file(output).expect("write src/sys.rs");
    println!("wrote {output}");
}
